#include "random_utils.h"

#include <math.h>
#include <stdlib.h>

void random_seed(unsigned int seed)
{
    // Задаём начальное значение генератора случайных чисел.
    // При одинаковом seed программа будет выдавать одинаковую последовательность случайных чисел.
    // Это удобно для отладки и повторяемости результатов.
    srand(seed);
}

double random_uniform(double min, double max)
{
    // rand() возвращает целое случайное число от 0 до RAND_MAX.
    // Делением на RAND_MAX переводим его в диапазон примерно от 0 до 1.
    double u = (double)rand() / (double)RAND_MAX;

    // Масштабируем число из диапазона [0, 1] в нужный диапазон [min, max].
    // Эта функция используется, например, в resampling для случайного выбора позиции.
    return min + (max - min) * u;
}

double random_normal(double mean, double stddev)
{
    const double pi = 3.14159265358979323846;

    // Для фильтра частиц нужен нормальный шум:
    // шум движения, шум скорости и шум измерений.
    // Стандартная функция rand() даёт равномерные числа, поэтому их нужно преобразовать.

    // Берём два равномерных случайных числа.
    // +1 и +2 нужны, чтобы u1 никогда не стало нулём.
    // Это важно, потому что ниже используется log(u1), а log(0) невозможен.
    double u1 = ((double)rand() + 1.0) / ((double)RAND_MAX + 2.0);
    double u2 = ((double)rand() + 1.0) / ((double)RAND_MAX + 2.0);

    // Преобразование Бокса-Мюллера превращает два равномерных числа
    // в число, распределённое примерно по нормальному закону.
    double radius = sqrt(-2.0 * log(u1));
    double angle = 2.0 * pi * u2;

    // Используем cos(angle), чтобы получить одно нормальное случайное значение.
    // Второе значение можно было бы получить через sin(angle), но в проекте оно не нужно.
    double z = radius * cos(angle);

    // z имеет среднее 0 и стандартное отклонение 1.
    // Сдвигаем его к нужному mean и растягиваем на stddev.
    return mean + stddev * z;
}